'use client';

import Link from 'next/link';
import { useState } from 'react';
import { Check, CircleSlash, MessageSquareText, RotateCcw } from 'lucide-react';
import { DIMENSIONS, RATING_LABEL } from '@/lib/rubric';
import type { ReviewPayload, Note } from '@/lib/types';
import type { CheckResult } from '@/lib/ai/compare';
import { LocalTime } from '../LocalTime';
import { Empty, QuoteButton, Section, SEVERITY_LABEL, SEVERITY_TEXT, type ItemState } from './shared';

type Filter = 'open' | 'high' | 'closed';

interface Props {
  review: ReviewPayload;
  itemStatus: Record<string, string>;
  stateOf: (id: string) => ItemState;
  activeId: string | null;
  onJump: (id: string) => void;
  onStatus: (id: string, status: 'open' | 'dismissed' | 'resolved') => void;
  onAsk: (note: Note) => void;
  draftChanged: boolean;
  check: { running: boolean; result: CheckResult | null; error: string | null };
  onCheck: () => void;
  essayId: string;
}

const RATING_STYLE = {
  strong: 'text-keep',
  developing: 'text-medium',
  needs_work: 'text-high',
  not_assessable: 'text-ink-3',
} as const;

const CHECK_LABEL = { addressed: 'Addressed', partly: 'Partly addressed', not_addressed: 'Not yet addressed', removed: 'Passage removed' } as const;

export function ReviewTab(p: Props) {
  const [filter, setFilter] = useState<Filter>('open');
  const r = p.review.result.review;
  if (!r)
    return (
      <div className="p-5">
        <Empty>The editorial part of this review did not complete: {p.review.result.errors.review ?? 'unknown error'}. Run the review again.</Empty>
      </div>
    );

  const closed = (id: string) => p.itemStatus[id] === 'dismissed' || p.itemStatus[id] === 'resolved';
  const notes = r.notes.filter((n) => (filter === 'closed' ? closed(n.id) : !closed(n.id) && (filter === 'open' || n.severity === 'high')));
  const openCount = r.notes.filter((n) => !closed(n.id)).length;
  const checkFor = (id: string) => p.check.result?.items.find((i) => i.noteId === id);
  const fit = r.promptFit;

  return (
    <div>
      {p.review.result.generatedAt && (
        <p className="border-b border-rule bg-desk px-5 py-2.5 text-[13px] text-ink-2">
          Sample review, generated by Stet&rsquo;s engine on <LocalTime date={p.review.result.generatedAt} format="date" />. Run a review to get a fresh one.
        </p>
      )}

      <Section title="Overall">
        <p className="text-[15px] leading-relaxed">{r.overall}</p>
        <dl className="mt-4 grid gap-3 text-[14px]">
          <div>
            <dt className="text-[12.5px] font-semibold text-ink-3">What a reader learns about you</dt>
            <dd className="mt-0.5">{r.takeaway}</dd>
          </div>
          <div>
            <dt className="text-[12.5px] font-semibold text-ink-3">Prompt</dt>
            <dd className="mt-0.5">
              <span className={`font-semibold ${fit.verdict === 'answers' ? 'text-keep' : fit.verdict === 'no_prompt' ? 'text-ink-2' : 'text-medium'}`}>
                {{ answers: 'Answers the prompt', partly: 'Partly answers the prompt', drifts: 'Drifts from the prompt', no_prompt: 'No prompt set' }[fit.verdict]}.
              </span>{' '}
              {fit.explanation}
            </dd>
          </div>
          <div>
            <dt className="text-[12.5px] font-semibold text-ink-3">Length</dt>
            <dd className={`mt-0.5 ${p.review.result.limits.over ? 'font-semibold text-high' : ''}`}>
              {p.review.result.limits.words} words, {p.review.result.limits.chars} characters
              {p.review.result.limits.message ? `: ${p.review.result.limits.message}.` : '.'}
            </dd>
          </div>
        </dl>
      </Section>

      {p.draftChanged && (
        <Section title="Since this review">
          <p className="text-[14px] text-ink-2">You have edited the draft. Check whether your changes address the notes, or review the new draft.</p>
          <div className="mt-3 flex flex-wrap gap-2">
            <button type="button" className="btn btn-sm" onClick={p.onCheck} disabled={p.check.running}>
              {p.check.running ? 'Checking…' : 'Check my revisions'}
            </button>
            <Link className="btn btn-sm btn-ghost no-underline" href={`/essays/${p.essayId}/compare?a=${p.review.versionId}`}>Compare drafts</Link>
          </div>
          {p.check.error && <p role="alert" className="mt-2 text-[13.5px] text-high">{p.check.error}</p>}
          {p.check.result && (
            <div className="mt-3 rounded-md bg-desk p-3 text-[14px]">
              <p>{p.check.result.summary}</p>
              <p className="mt-2 text-[12.5px] text-ink-3">AI assessment by {p.check.result.model}. Statuses appear on each note below.</p>
            </div>
          )}
        </Section>
      )}

      {r.plan.length > 0 && (
        <Section title="Revision plan">
          <ol className="grid gap-3">
            {r.plan.map((s, i) => (
              <li key={i} className="grid grid-cols-[22px_1fr] gap-1 text-[14px]">
                <span className="font-semibold text-ink-3">{i + 1}.</span>
                <div>
                  <p className="font-semibold leading-snug">{s.step}</p>
                  <p className="text-ink-2">{s.why}</p>
                  {s.noteIds.length > 0 && (
                    <div className="mt-1 flex flex-wrap gap-1.5">
                      {s.noteIds.map((id) => {
                        const n = r.notes.find((x) => x.id === id);
                        return n ? (
                          <button key={id} type="button" className="text-[12.5px] text-pencil underline-offset-2 hover:underline" onClick={() => p.onJump(id)}>
                            {n.title}
                          </button>
                        ) : null;
                      })}
                    </div>
                  )}
                </div>
              </li>
            ))}
          </ol>
        </Section>
      )}

      <Section
        title={`Notes (${openCount} open)`}
        aside={
          <div className="flex gap-1 text-[12.5px]" role="tablist" aria-label="Filter notes">
            {(['open', 'high', 'closed'] as const).map((f) => (
              <button
                key={f}
                role="tab"
                aria-selected={filter === f}
                type="button"
                className="rounded px-2 py-0.5 text-ink-2 hover:bg-desk-2 aria-selected:bg-pencil-wash aria-selected:font-semibold aria-selected:text-ink"
                onClick={() => setFilter(f)}
              >
                {{ open: 'Open', high: 'High', closed: 'Done' }[f]}
              </button>
            ))}
          </div>
        }
      >
        {notes.length === 0 && <Empty>{filter === 'closed' ? 'Nothing resolved or dismissed yet.' : 'No open notes in this view.'}</Empty>}
        <ul className="grid gap-1">
          {notes.map((n) => {
            const st = p.stateOf(n.id);
            const chk = checkFor(n.id);
            return (
              <li
                key={n.id}
                id={`item-${n.id}`}
                className={`-mx-2 rounded-lg px-2 py-3 ${p.activeId === n.id ? 'bg-pencil-wash/60' : ''}`}
              >
                <div className="flex items-start gap-2">
                  <span className={`mark mark-${n.severity} mt-[6px]`} aria-hidden />
                  <div className="min-w-0 flex-1">
                    <div className="flex flex-wrap items-baseline gap-x-2">
                      <h4 className="text-[14.5px] font-semibold leading-snug">{n.title}</h4>
                      <span className={`text-[12px] ${SEVERITY_TEXT[n.severity]}`}>{SEVERITY_LABEL[n.severity]}</span>
                      <span className="text-[12px] text-ink-3">· {DIMENSIONS[n.dimension]?.name ?? n.dimension}</span>
                      {n.confidence === 'low' && <span className="text-[12px] text-ink-3">· lower confidence</span>}
                    </div>
                    <QuoteButton anchor={n.anchor} state={st} onJump={() => p.onJump(n.id)} />
                    {chk && (
                      <p className={`mt-2 text-[13px] ${chk.status === 'addressed' || chk.status === 'removed' ? 'text-keep' : chk.status === 'partly' ? 'text-medium' : 'text-high'}`}>
                        <span className="font-semibold">{CHECK_LABEL[chk.status]}.</span> <span className="text-ink-2">{chk.explanation}</span>
                      </p>
                    )}
                    <p className="mt-2 text-[14px] leading-relaxed text-ink-2">{n.why}</p>
                    <p className="mt-1.5 text-[14px] leading-relaxed"><span className="font-semibold">Try: </span>{n.action}</p>
                    {n.example && (
                      <p className="mt-1.5 text-[14px] leading-relaxed text-ink-2">
                        <span className="font-semibold text-ink">One possible direction: </span>
                        <span className="quote">{n.example}</span>
                      </p>
                    )}
                    {n.question && <p className="mt-1.5 text-[14px] italic leading-relaxed text-ink-2">{n.question}</p>}
                    <div className="mt-2.5 flex flex-wrap gap-1">
                      <button type="button" className="btn btn-ghost btn-sm" onClick={() => p.onAsk(n)}>
                        <MessageSquareText size={14} aria-hidden /> Work on this
                      </button>
                      {closed(n.id) ? (
                        <button type="button" className="btn btn-ghost btn-sm" onClick={() => p.onStatus(n.id, 'open')}>
                          <RotateCcw size={14} aria-hidden /> Reopen
                        </button>
                      ) : (
                        <>
                          <button type="button" className="btn btn-ghost btn-sm" onClick={() => p.onStatus(n.id, 'resolved')}>
                            <Check size={14} aria-hidden /> Resolved
                          </button>
                          <button type="button" className="btn btn-ghost btn-sm" onClick={() => p.onStatus(n.id, 'dismissed')}>
                            <CircleSlash size={14} aria-hidden /> Dismiss
                          </button>
                        </>
                      )}
                    </div>
                  </div>
                </div>
              </li>
            );
          })}
        </ul>
        {p.check.result && p.check.result.newIssues.length > 0 && (
          <div className="mt-4 border-t border-rule pt-4">
            <h4 className="text-[14px] font-semibold">New in this revision</h4>
            <ul className="mt-2 grid gap-3 text-[14px]">
              {p.check.result.newIssues.map((x) => (
                <li key={x.id}>
                  <div className="flex items-center gap-2 font-semibold"><span className={`mark mark-${x.severity}`} aria-hidden />{x.title}</div>
                  <p className="quote mt-1 text-ink-2">&ldquo;{x.anchor.quote}&rdquo;</p>
                  <p className="text-ink-2">{x.why}</p>
                </li>
              ))}
            </ul>
          </div>
        )}
      </Section>

      {r.strengths.length > 0 && (
        <Section title="What is working">
          <ul className="grid gap-4">
            {r.strengths.map((s) => (
              <li key={s.id} id={`item-${s.id}`} className="text-[14px]">
                <QuoteButton anchor={s.anchor} state={p.stateOf(s.id)} onJump={() => p.onJump(s.id)} tone="keep" />
                <p className="mt-1.5 leading-relaxed text-ink-2">{s.why}</p>
              </li>
            ))}
          </ul>
        </Section>
      )}

      <Section title="Rubric" aside={<Link href="/method#rubric" className="text-[12.5px] text-ink-3">What the levels mean</Link>}>
        <ul className="grid gap-2.5">
          {r.dimensions.map((d) => (
            <li key={d.key} className="grid grid-cols-[minmax(0,1fr)_auto] gap-x-3 text-[14px]">
              <span className="font-semibold">{DIMENSIONS[d.key].name}</span>
              <span className={`text-right text-[13px] font-semibold ${RATING_STYLE[d.rating]}`}>{RATING_LABEL[d.rating]}</span>
              <span className="col-span-2 text-[13.5px] leading-snug text-ink-2">{d.rationale}</span>
            </li>
          ))}
        </ul>
        <p className="mt-3 text-[12.5px] text-ink-3">Ratings are an editor&rsquo;s judgement against written criteria, not a prediction of admission.</p>
      </Section>

      {r.questions.length > 0 && (
        <Section title="Questions to think about">
          <ul className="grid list-disc gap-2 pl-5 text-[14px] leading-relaxed text-ink-2 marker:text-ink-3">
            {r.questions.map((q, i) => <li key={i}>{q}</li>)}
          </ul>
        </Section>
      )}

      {(r.caveats.length > 0 || r.dropped > 0) && (
        <Section title="Limits of this review">
          <ul className="grid gap-1.5 text-[13.5px] text-ink-2">
            {r.caveats.map((c, i) => <li key={i}>{c}</li>)}
            {r.dropped > 0 && (
              <li>
                {r.dropped} {r.dropped === 1 ? 'comment' : 'comments'} quoted words that are not in your essay and {r.dropped === 1 ? 'was' : 'were'} discarded.
              </li>
            )}
          </ul>
        </Section>
      )}

      <p className="border-t border-rule px-5 py-4 text-[12.5px] text-ink-3">
        Reviewed <LocalTime date={p.review.createdAt} /> by {r.model}. AI feedback can be wrong; you decide what to change.
      </p>
    </div>
  );
}
